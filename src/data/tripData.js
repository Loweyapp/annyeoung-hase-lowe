// Helper: parse date string to Date object
export function parseDate(dateStr) {
  const [y, m, d] = dateStr.split('-').map(Number)
  return new Date(y, m - 1, d)
}

// Helper: format date for display
export function formatDate(dateStr) {
  const date = parseDate(dateStr)
  return date.toLocaleDateString('en-GB', { weekday: 'short', day: 'numeric', month: 'long', year: 'numeric' })
}

export function formatDateShort(dateStr) {
  const date = parseDate(dateStr)
  return date.toLocaleDateString('en-GB', { weekday: 'short', day: 'numeric', month: 'short' })
}

// Today's day in the trip (null if before/after)
export function getTodayDay() {
  const today = new Date()
  today.setHours(0, 0, 0, 0)
  return TRIP.days.find(d => {
    const dd = parseDate(d.date)
    return dd.getTime() === today.getTime()
  }) || null
}

export function getDaysUntilTrip() {
  const today = new Date()
  today.setHours(0, 0, 0, 0)
  const start = parseDate(TRIP.startDate)
  const diff = Math.ceil((start - today) / (1000 * 60 * 60 * 24))
  return diff
}

export function isTripOver() {
  const today = new Date()
  today.setHours(0, 0, 0, 0)
  const end = parseDate(TRIP.endDate)
  return today > end
}
