// ── Helpers ──────────────────────────────────────────────────

export function parseDate(dateStr) {
  const [y, m, d] = dateStr.split('-').map(Number)
  return new Date(y, m - 1, d)
}

export function formatDate(dateStr) {
  return parseDate(dateStr).toLocaleDateString('en-GB', {
    weekday: 'short', day: 'numeric', month: 'long', year: 'numeric',
  })
}

export function formatDateShort(dateStr) {
  return parseDate(dateStr).toLocaleDateString('en-GB', {
    weekday: 'short', day: 'numeric', month: 'short',
  })
}

export function getTodayDay() {
  const today = new Date()
  today.setHours(0, 0, 0, 0)
  return TRIP.days.find(d => {
    const dd = parseDate(d.date)
    return dd.getTime() === today.getTime()
  }) || null
}

export function getDaysUntilTrip() {
  const today = new Date()
  today.setHours(0, 0, 0, 0)
  const start = parseDate(TRIP.startDate)
  return Math.ceil((start - today) / (1000 * 60 * 60 * 24))
}

export function isTripOver() {
  const today = new Date()
  today.setHours(0, 0, 0, 0)
  return today > parseDate(TRIP.endDate)
}

// Group days by segment, preserving order
export function getDaysBySegment() {
  const segments = []
  let current = null
  for (const day of TRIP.days) {
    if (!current || current.segment !== day.segment) {
      current = {
        segment: day.segment,
        country: day.country,
        label: SEGMENT_LABELS[day.segment],
        days: [],
      }
      segments.push(current)
    }
    current.days.push(day)
  }
  return segments
}

